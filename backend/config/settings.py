database_url = os.getenv("DATABASE_URL")
if database_url:
    import dj_database_url

    database = dj_database_url.parse(database_url, conn_max_age=60, conn_health_checks=True)
    if database["ENGINE"] != "django.db.backends.postgresql":
        raise ImproperlyConfigured("DATABASE_URL must point to a PostgreSQL database.")
    database.setdefault("OPTIONS", {}).setdefault("sslmode", "require")
    DATABASES = {"default": database}
elif os.getenv("POSTGRES_DB"):
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": os.environ["POSTGRES_DB"],
            "USER": os.environ["POSTGRES_USER"],
            "PASSWORD": os.getenv("POSTGRES_PASSWORD", ""),
            "HOST": os.getenv("POSTGRES_HOST", "localhost"),
            "PORT": os.getenv("POSTGRES_PORT", "5432"),
        },
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": os.getenv("DJANGO_SQLITE_PATH") or BASE_DIR / "db.sqlite3",
        },
    }

